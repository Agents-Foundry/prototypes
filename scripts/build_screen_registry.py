#!/usr/bin/env python3
"""Generate the machine-readable screen registry from the prototype apps.

Reads each app's screens-*.js, writes screen-registry/screens.csv and
screen-registry/SCREENS.md. Every screen is a PROPOSAL; this file records
inventory, not approval. Use --check in CI to ensure the files are current.
"""
from __future__ import annotations
import argparse
import csv
import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APPS = [
    ("PLT", "Platform Owner", "platform-owner/app", 22),
    ("ORG", "Organization Admin", "organization-admin/app", 13),
    ("EMP", "Employee Desktop", "employee-desktop/app", 16),
    ("STD", "Agent Studio", "agent-studio/app", 0),
]
ENTRY = re.compile(r"S\d?\['([A-Z]{3}-\d{3})'\]=\{title:'((?:[^'\\]|\\.)*)'")
GROUP = re.compile(r"group:'((?:[^'\\]|\\.)*)'")


def collect():
    rows = []
    for prefix, label, folder, legacy_max in APPS:
        for path in sorted((ROOT / folder).glob("screens-*.js")):
            text = path.read_text(encoding="utf-8")
            for m in ENTRY.finditer(text):
                sid, title = m.group(1), m.group(2).replace("\\'", "'")
                g = GROUP.search(text, m.end(), m.end() + 400)
                num = int(sid.split("-")[1])
                rows.append({
                    "id": sid,
                    "surface": label,
                    "title": title,
                    "group": g.group(1) if g else "",
                    "source": f"{folder}/{path.name}",
                    "origin": "redesign of legacy ID" if num <= legacy_max else "new",
                    "status": "proposed",
                })
    rows.sort(key=lambda r: r["id"])
    return rows


def render(rows):
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()), lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    csv_text = buf.getvalue()

    lines = ["# Screen registry (generated)", "",
             "Generated by `python scripts/build_screen_registry.py`. **Every screen is a proposal.** "
             "Listing here is inventory, not review, acceptance or design freeze.", ""]
    for prefix, label, folder, _ in APPS:
        sub = [r for r in rows if r["id"].startswith(prefix)]
        lines += [f"## {label} ({len(sub)} screens) · [`{folder}/`](../{folder}/index.html)", "",
                  "| ID | Screen | Group | Origin |", "| --- | --- | --- | --- |"]
        lines += [f"| {r['id']} | {r['title']} | {r['group']} | {r['origin']} |" for r in sub]
        lines.append("")
    lines.append(f"**Total: {len(rows)} screens.**")
    return csv_text, "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()
    rows = collect()
    if not rows:
        print("No screens found", file=sys.stderr)
        return 1
    csv_text, md_text = render(rows)
    out = ROOT / "screen-registry"
    targets = {out / "screens.csv": csv_text, out / "SCREENS.md": md_text}
    if args.check:
        stale = [p.name for p, t in targets.items()
                 if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != t]
        if stale:
            print("STALE: " + ", ".join(stale) + " (run scripts/build_screen_registry.py)", file=sys.stderr)
            return 1
        print(f"PASS: screen registry is current ({len(rows)} screens)")
        return 0
    for p, t in targets.items():
        p.write_text(t, encoding="utf-8", newline="\n")
    print(f"Wrote {len(rows)} screens to screen-registry/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
